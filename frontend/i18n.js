let currentLang = 'fr';

function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) lang = 'fr';
    currentLang = lang;
    localStorage.setItem('devis_lang', lang);
    document.documentElement.lang = lang;
    applyTranslations();
}

function getLanguage() {
    return currentLang;
}

function t(key) {
    return TRANSLATIONS[currentLang]?.[key] || TRANSLATIONS['fr']?.[key] || key;
}

function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const value = t(key);
        if (value && value !== key) {
            if (el.children.length === 0) {
                // Élément sans enfants : on peut mettre innerHTML (utile pour les <br/>)
                el.innerHTML = value;
            } else {
                // Élément avec enfants (ex: <h1>Devis <span>Express</span> Pro</h1>) : on remplace uniquement le noeud texte direct
                for (const node of el.childNodes) {
                    if (node.nodeType === 3 && node.textContent.trim()) {
                        node.textContent = value;
                        break;
                    }
                }
            }
        }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.placeholder = t(key);
    });
}

(function initI18n() {
    const saved = localStorage.getItem('devis_lang');
    if (saved && TRANSLATIONS[saved]) {
        currentLang = saved;
        document.documentElement.lang = saved;
    }
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', applyTranslations);
    } else {
        applyTranslations();
    }
})();